export const generateBackgroundStars = (count = 10000, radius = 30000) => {
  const positions = new Float32Array(count * 3);
  const colors = new Float32Array(count * 3);
  const sizes = new Float32Array(count);
  
  const colorPalette = [
    new THREE.Color('#ffffff'), // White
    new THREE.Color('#aaccff'), // Blueish
    new THREE.Color('#ffccaa'), // Orange
    new THREE.Color('#ff9999'), // Reddish
    new THREE.Color('#99ccff')  // Light Blue
  ];
  
  for (let i = 0; i < count; i++) {
    // Generate points on a sphere using spherical coordinates
    const theta = 2 * Math.PI * Math.random();
    const phi = Math.acos(2 * Math.random() - 1);
    
    // Add some random variation to radius for depth
    const r = radius + (Math.random() - 0.5) * (radius * 0.5);
    
    positions[i * 3] = r * Math.sin(phi) * Math.cos(theta);
    positions[i * 3 + 1] = r * Math.sin(phi) * Math.sin(theta);
    positions[i * 3 + 2] = r * Math.cos(phi);
    
    // Assign a random color
    const color = colorPalette[Math.floor(Math.random() * colorPalette.length)];
    colors[i * 3] = color.r;
    colors[i * 3 + 1] = color.g;
    colors[i * 3 + 2] = color.b;
    
    // Assign a random size
    sizes[i] = Math.random() * 2.0 + 0.5;
  }
  return { positions, colors, sizes };
};
